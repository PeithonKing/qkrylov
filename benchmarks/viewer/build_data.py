#!/usr/bin/env python3
"""Merge the JSON files written by benchmarks/bench_matrix.py into data.js for the viewer.

    python benchmarks/viewer/build_data.py benchmarks/results/matrix/*.json

One dataset per machine, device (CPU or GPU) and mode, so a server with a GPU gives two datasets per mode.
"""
import json
import re
import sys
from pathlib import Path

MODE_LABEL = {"fixed": "No early stopping (100 iterations)", "early": "Early stopping (converged)"}
groups = {}
for path in sys.argv[1:]:
    blob = json.loads(Path(path).read_text())
    meta = blob["meta"]
    for dev in sorted({r["device"] for r in blob["results"]}):
        g = groups.setdefault((meta["machine"], dev, meta["mode"]), {"metas": [], "results": []})
        g["metas"].append(meta)
        g["results"] += [r for r in blob["results"] if r["device"] == dev]

datasets = []
GPU_NAME = {"susskind": "RTX 4500 Ada"}
for (machine, dev, mode), g in sorted(groups.items(), key=lambda kv: (kv[0][2] != "fixed", kv[0][0].startswith("Raspberry"), kv[0][0].startswith("Laptop"), kv[0][1] == "gpu")):
    m = g["metas"][0]
    name = machine.split(" (")[0]
    hw = f"{GPU_NAME.get(name, 'GPU')} GPU" if dev == "gpu" else f"{m['cores']}-core CPU"
    label = f"{name} {'GPU' if dev == 'gpu' else 'CPU'}"
    tol = m["tol"] if mode == "early" else None
    info = (f"{name}: {hw}. Periodic Heisenberg chain, Sz = 0, "
            f"Lanczos ground state, {m['date']}. "
            + (f"Exactly {m['maxiter']} iterations." if mode == "fixed" else
               f"Stops when converged (tol FP32 {tol['32']:g}, FP64 {tol['64']:g}), at most {m['maxiter']} iterations."))
    datasets.append({"id": re.sub(r"\W+", "_", f"{name}_{dev}_{mode}").strip("_").lower(),
                     "label": f"{label} — {MODE_LABEL[mode]}", "machine": f"{name} {dev}", "mode": mode, "info": info,
                     "results": sorted(g["results"], key=lambda r: (r["L"], r["precision"], r["device"], r["passes"]))})

out = Path(__file__).with_name("data.js")
out.write_text("// Generated by build_data.py from the bench_matrix.py JSON files; do not edit.\n"
               "window.BENCH_DATA = " + json.dumps({"datasets": datasets}, indent=1) + ";\n")
print(f"wrote {out} with {len(datasets)} datasets, {sum(len(d['results']) for d in datasets)} results")
